create table if not exists admin_users (
  user_id    uuid primary key,
  role       text not null default 'admin' check (role in ('owner','admin','support')),
  active     boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists admin_audit (
  id         bigint generated by default as identity primary key,
  actor_id   uuid,
  action     text not null,
  entity     text not null,
  entity_id  text,
  created_at timestamptz not null default now()
);

create table if not exists profiles (
  id         uuid primary key,
  email      text,
  full_name  text,
  created_at timestamptz not null default now()
);

create table if not exists categories (
  key          text primary key,
  name_az      text not null,
  name_ru      text,
  name_en      text,
  icon         text,
  visual_style text not null default 'default',
  sort_order   int  not null default 0,
  active       boolean not null default true,
  created_at   timestamptz not null default now()
);

-- id-lər text-dir ki, köhnə Supabase-dən həm rəqəm, həm uuid köçə bilsin
create table if not exists site_products (
  product_key    text primary key,
  name           text,
  name_az        text,
  name_ru        text,
  name_en        text,
  slug           text,
  category_key   text,
  description_az text,
  description_ru text,
  description_en text,
  features_az    jsonb not null default '[]'::jsonb,
  features_ru    jsonb not null default '[]'::jsonb,
  features_en    jsonb not null default '[]'::jsonb,
  image_url      text,
  sort_order     int not null default 0,
  is_featured    boolean not null default false,
  active         boolean not null default true,
  seo            jsonb not null default '{}'::jsonb,
  created_at     timestamptz not null default now()
);

create table if not exists product_prices (
  product_key   text primary key,
  product_name  text,
  price_1_month  numeric(10,2),
  price_2_month  numeric(10,2),
  price_3_month  numeric(10,2),
  price_6_month  numeric(10,2),
  price_12_month numeric(10,2),
  sale_1_price   numeric(10,2),
  sale_2_price   numeric(10,2),
  sale_3_price   numeric(10,2),
  sale_6_price   numeric(10,2),
  sale_12_price  numeric(10,2),
  sale_1_active  boolean not null default false,
  sale_2_active  boolean not null default false,
  sale_3_active  boolean not null default false,
  sale_6_active  boolean not null default false,
  sale_12_active boolean not null default false,
  updated_at     timestamptz not null default now()
);

create table if not exists site_faqs (
  id          text primary key default gen_random_uuid()::text,
  product_key text,
  question    text not null,
  answer      text not null,
  language    text not null default 'az',
  sort_order  int not null default 0,
  active      boolean not null default true,
  created_at  timestamptz not null default now()
);

create table if not exists orders (
  id         text primary key default gen_random_uuid()::text,
  user_id    uuid,
  total      numeric(12,2) not null default 0,
  status     text not null default 'pending',
  items      jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists messages (
  id          text primary key default gen_random_uuid()::text,
  user_id     uuid not null,
  sender_role text not null check (sender_role in ('customer','admin')),
  message     text not null,
  is_read     boolean not null default false,
  created_at  timestamptz not null default now()
);

create table if not exists banners (
  id           uuid primary key default gen_random_uuid(),
  title_az text, title_ru text, title_en text,
  subtitle_az text, subtitle_ru text, subtitle_en text,
  cta_label_az text, cta_label_ru text, cta_label_en text,
  cta_url      text,
  image_url    text,
  sort_order   int not null default 0,
  active       boolean not null default true,
  created_at   timestamptz not null default now()
);

create table if not exists reviews (
  id           uuid primary key default gen_random_uuid(),
  author_name  text not null,
  rating       smallint not null default 5 check (rating between 1 and 5),
  body_az text, body_ru text, body_en text,
  review_date  date not null default current_date,
  status       text not null default 'pending' check (status in ('pending','approved','rejected')),
  show_on_home boolean not null default false,
  sort_order   int not null default 0,
  source       text not null default 'admin' check (source in ('admin','customer')),
  user_id      uuid,
  created_at   timestamptz not null default now()
);

create table if not exists site_content (
  key        text not null,
  lang       text not null check (lang in ('az','ru','en')),
  value      text,
  updated_at timestamptz not null default now(),
  primary key (key, lang)
);

create table if not exists site_settings (
  key        text primary key,
  value      jsonb not null default 'null'::jsonb,
  updated_at timestamptz not null default now()
);

create index if not exists orders_user_idx    on orders (user_id, created_at desc);
create index if not exists messages_user_idx  on messages (user_id, created_at);
create index if not exists reviews_status_idx on reviews (status, show_on_home);
